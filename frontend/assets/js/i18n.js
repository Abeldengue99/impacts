const I18n = {
  currentLang: localStorage.getItem('impacta_lang') || 'pt-AO',

  setLanguage(lang) {
    if (I18N_TRANSLATIONS[lang]) {
      this.currentLang = lang;
      localStorage.setItem('impacta_lang', lang);
      document.documentElement.lang = lang;
      // Disparar evento para re-renderização suave da UI
      window.dispatchEvent(new CustomEvent('impacta:langchange', { detail: { lang } }));
      if (window.Toast) {
        const names = { 'pt-AO': 'Português (AO)', 'en': 'English', 'fr': 'Français', 'zh': '中文' };
        window.Toast.info(`Idioma alterado para: ${names[lang] || lang}`);
      }
    }
  },

  t(path) {
    const keys = path.split('.');
    let res = I18N_TRANSLATIONS[this.currentLang];
    for (const key of keys) {
      if (res && res[key] !== undefined) {
        res = res[key];
      } else {
        // Fallback para pt-AO
        let fallback = I18N_TRANSLATIONS['pt-AO'];
        for (const fKey of keys) {
          fallback = fallback ? fallback[fKey] : undefined;
        }
        return fallback || path;
      }
    }
    return res;
  }
};

window.I18n = I18n;

